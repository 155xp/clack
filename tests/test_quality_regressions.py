"""Output protection and opt-in compiler phase measurements."""

from contextlib import redirect_stderr, redirect_stdout
import io
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

from clack.cli import main


ROOT = Path(__file__).resolve().parents[1]
CC = shutil.which("cc")
SOURCE = "fn main():\n    print(42)\n"


class OutputProtectionTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="clack-quality-")
        self.addCleanup(temporary.cleanup)
        self.directory = Path(temporary.name)
        self.source = self.directory / "main.clack"
        self.source.write_text(SOURCE, encoding="utf-8")

    def cli(self, *arguments):
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            status = main(list(map(str, arguments)))
        return status, stdout.getvalue(), stderr.getvalue()

    def test_emit_c_preserves_input_when_output_is_a_hardlink(self):
        output = self.directory / "program.c"
        os.link(self.source, output)
        status, _, error = self.cli("emit-c", self.source, "-o", output)
        self.assertEqual(status, 0, error)
        self.assertEqual(self.source.read_text(encoding="utf-8"), SOURCE)
        self.assertIn("Generated by Clack", output.read_text(encoding="utf-8"))
        self.assertFalse(output.samefile(self.source))

    def test_failed_emit_c_preserves_existing_output_and_cleans_temporary_files(self):
        output = self.directory / "program.c"
        output.write_text("previous C output", encoding="utf-8")
        with patch("clack.cli.os.replace", side_effect=OSError("simulated replacement failure")):
            status, _, error = self.cli("emit-c", self.source, "-o", output)
        self.assertEqual(status, 1)
        self.assertIn("simulated replacement failure", error)
        self.assertEqual(output.read_text(encoding="utf-8"), "previous C output")
        self.assertEqual(self.source.read_text(encoding="utf-8"), SOURCE)
        self.assertEqual(sorted(path.name for path in self.directory.iterdir()), ["main.clack", "program.c"])

    def test_proof_exports_cannot_overwrite_an_input_with_an_artifact_name(self):
        for name in ("obligations.json", "0001.smt2", "10000.smt2"):
            with self.subTest(name=name):
                source = self.directory / name
                source.write_text(SOURCE, encoding="utf-8")
                try:
                    status, _, error = self.cli("check", source, "--proof-dir", self.directory)
                    self.assertEqual(status, 1)
                    self.assertIn("proof outputs must differ", error)
                    self.assertEqual(source.read_text(encoding="utf-8"), SOURCE)
                finally:
                    source.unlink()

    def test_proof_exports_protect_imported_and_native_inputs_through_links(self):
        library = self.directory / "library.clack"
        library_text = 'native "provider.c"\nextern fn value() -> int = "clack_test_value"\n'
        library.write_text(library_text, encoding="utf-8")
        provider = self.directory / "provider.c"
        provider_text = "#include <stdint.h>\nint64_t clack_test_value(void) { return 7; }\n"
        provider.write_text(provider_text, encoding="utf-8")
        self.source.write_text("from library import value\nfn main():\n    answer = value()\n    print(answer)\n", encoding="utf-8")
        proofs = self.directory / "proofs"
        proofs.mkdir()
        for target in (self.source, library, provider):
            for kind in ("hardlink", "symlink"):
                with self.subTest(target=target.name, kind=kind):
                    artifact = proofs / "0001.smt2"
                    if kind == "hardlink":
                        os.link(target, artifact)
                    else:
                        artifact.symlink_to(target)
                    original = target.read_bytes()
                    try:
                        status, _, error = self.cli("check", self.source, "--proof-dir", proofs)
                        self.assertEqual(status, 1)
                        self.assertIn("proof outputs must differ", error)
                        self.assertEqual(target.read_bytes(), original)
                        self.assertFalse((proofs / "obligations.json").exists())
                    finally:
                        artifact.unlink()

    def test_proof_exports_still_work_in_an_ordinary_directory(self):
        proofs = self.directory / "proofs"
        status, _, error = self.cli("check", self.source, "--proof-dir", proofs)
        self.assertEqual(status, 0, error)
        self.assertTrue((proofs / "0001.smt2").is_file())
        self.assertTrue((proofs / "obligations.json").is_file())


class TimingTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="clack-timings-")
        self.addCleanup(temporary.cleanup)
        self.directory = Path(temporary.name)
        self.source = self.directory / "main.clack"
        self.source.write_text(SOURCE, encoding="utf-8")

    def cli(self, command, *arguments):
        return subprocess.run([sys.executable, "-m", "clack", command, str(self.source), *map(str, arguments)],
                              cwd=ROOT, text=True, capture_output=True, timeout=30)

    def phases(self, stderr):
        self.assertTrue(stderr.startswith("clack timings: "), stderr)
        entries = stderr.removeprefix("clack timings: ").strip().split(", ")
        for entry in entries:
            self.assertRegex(entry, r"^[a-z]+=[0-9]+\.[0-9]{2}ms$")
        return [entry.split("=", 1)[0] for entry in entries]

    def test_check_and_emit_timings_are_opt_in_and_use_standard_error(self):
        for command, wanted in (("check", ["load", "verify"]), ("emit-c", ["load", "verify", "emit"])):
            with self.subTest(command=command):
                ordinary = self.cli(command)
                measured = self.cli(command, "--timings")
                self.assertEqual(ordinary.returncode, 0, ordinary.stderr)
                self.assertEqual(measured.returncode, 0, measured.stderr)
                self.assertEqual(ordinary.stderr, "")
                self.assertEqual(measured.stdout, ordinary.stdout)
                self.assertEqual(self.phases(measured.stderr), wanted)

    @unittest.skipUnless(CC, "build and run timings require a C11 compiler")
    def test_build_and_run_report_compiler_phases_and_preserve_program_output(self):
        for command in ("build", "run"):
            with self.subTest(command=command):
                arguments = ("-o", self.directory / "program") if command == "build" else ()
                result = self.cli(command, *arguments, "--cc", CC, "--timings")
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertEqual(self.phases(result.stderr), ["load", "verify", "emit", "cc"])
                if command == "run":
                    self.assertEqual(result.stdout, "42\n")

    def test_failed_phase_is_measured_without_hiding_the_source_error(self):
        self.source.write_text("fn main():\n    print(1 / 0)\n", encoding="utf-8")
        result = self.cli("check", "--timings")
        self.assertEqual(result.returncode, 1)
        self.assertIn("cannot prove division", result.stderr)
        self.assertRegex(result.stderr, r"clack timings: load=[0-9.]+ms, verify=[0-9.]+ms\n$")


if __name__ == "__main__":
    unittest.main()
